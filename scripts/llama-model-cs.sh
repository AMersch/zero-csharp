#!/usr/bin/env bash
# Writes models/stories260K.bin and models/tok512.bin as C# byte literals:
# the class Stories260K, with Model and Tokenizer as ReadOnlySpan<byte>, which
# the compiler stores in the program's data, read in place.
# Used by build.sh (the Llama sample) and sdk/pack.sh (ZeroCSharp.Stories260K).
# od is in coreutils, so this works in the build container too.
#
# Usage:  scripts/llama-model-cs.sh <out.cs>    (redone only when a model file is newer)
set -euo pipefail
out=${1:?out.cs}
root=$(cd "$(dirname "$0")/.." && pwd)
model=$root/models/stories260K.bin
tokenizer=$root/models/tok512.bin
if [ -f "$out" ] && [ ! "$model" -nt "$out" ] && [ ! "$tokenizer" -nt "$out" ]; then exit 0; fi
mkdir -p "$(dirname "$out")"
bytes() { od -An -v -tu1 "$1" | sed -E 's/ +$//; s/^ +//; s/ +/, /g; /./s/$/,/'; }
{
    echo "// Generated by scripts/llama-model-cs.sh from models/: don't edit."
    echo "// stories260K and its tokenizer, by Andrej Karpathy (MIT license):"
    echo "// https://huggingface.co/karpathy/tinyllamas"
    echo "public static class Stories260K"
    echo "{"
    echo "    /// <summary>The model, in llama2.c's format.</summary>"
    echo "    public static System.ReadOnlySpan<byte> Model => ["
    bytes "$model"
    echo "    ];"
    echo "    /// <summary>The 512-token tokenizer, in llama2.c's format.</summary>"
    echo "    public static System.ReadOnlySpan<byte> Tokenizer => ["
    bytes "$tokenizer"
    echo "    ];"
    echo "}"
} > "$out.tmp"
mv "$out.tmp" "$out"
